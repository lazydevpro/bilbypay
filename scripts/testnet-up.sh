#!/usr/bin/env bash
# Deploys BilbyPay to Monad testnet (or any EVM RPC) with mock dollars, and writes server/.env.testnet
# so the API runs with every outside service mocked: SMS codes (000000), gift cards, top-ups and a
# test-money faucet. Safe to re-run: role keys are reused from the existing env file.
#
#   DEPLOYER_PRIVATE_KEY=0x… ./scripts/testnet-up.sh
#
# Env: DEPLOYER_PRIVATE_KEY (required, holds testnet MON), RPC_URL (default Monad testnet),
#      FUND_MON (MON sent to the relayer, default 1), TREASURY_FLOAT_USD (default 10000),
#      ENV_OUT (default server/.env.testnet), PUBLIC_BASE_URL, SOLC (path to a solc binary, optional).
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
RPC_URL=${RPC_URL:-https://testnet-rpc.monad.xyz}
ENV_OUT=${ENV_OUT:-$ROOT/server/.env.testnet}
FUND_MON=${FUND_MON:-1}
TREASURY_FLOAT_USD=${TREASURY_FLOAT_USD:-10000}
: "${DEPLOYER_PRIVATE_KEY:?set DEPLOYER_PRIVATE_KEY to a key holding testnet MON}"

CHAIN_ID=$(cast chain-id --rpc-url "$RPC_URL")
if [ "$CHAIN_ID" = "143" ] && [ -n "$(cast code 0x00000000eFE302BEAA2b3e6e1b18d08D69a9012a --rpc-url "$RPC_URL" | sed 's/^0x$//')" ]; then
  echo "This is Monad mainnet; this script deploys mocks. Use contracts/script/Deploy.s.sol instead." >&2
  exit 1
fi
DEPLOYER=$(cast wallet address "$DEPLOYER_PRIVATE_KEY")
echo "chain $CHAIN_ID via $RPC_URL; deployer $DEPLOYER ($(cast balance "$DEPLOYER" --ether --rpc-url "$RPC_URL") MON)"

# Role keys: reuse from a previous run so addresses (and the verifier/treasury) stay stable.
getenv() { [ -f "$ENV_OUT" ] && grep -E "^$1=" "$ENV_OUT" | head -1 | cut -d= -f2- || true; }
newkey() { cast wallet new --json | jq -r '.[0].private_key'; }
RELAYER_KEY=$(getenv RELAYER_PRIVATE_KEY); RELAYER_KEY=${RELAYER_KEY:-$(newkey)}
VERIFIER_KEY=$(getenv VERIFIER_PRIVATE_KEY); VERIFIER_KEY=${VERIFIER_KEY:-$(newkey)}
TREASURY_KEY=$(getenv TREASURY_PRIVATE_KEY); TREASURY_KEY=${TREASURY_KEY:-$(newkey)}
RELAYER=$(cast wallet address "$RELAYER_KEY")
VERIFIER=$(cast wallet address "$VERIFIER_KEY")
TREASURY=$(cast wallet address "$TREASURY_KEY")
rand32() { echo "0x$(openssl rand -hex 32)"; }

# The relayer pays all gas (it is also the keeper). Users, verifier and treasury never hold MON.
RELAYER_WEI=$(cast balance "$RELAYER" --rpc-url "$RPC_URL")
WANT_WEI=$(cast to-wei "$FUND_MON")
if [ "$(echo "$RELAYER_WEI < $WANT_WEI" | bc)" = "1" ]; then
  echo "funding relayer $RELAYER with $FUND_MON MON"
  cast send --rpc-url "$RPC_URL" --private-key "$DEPLOYER_PRIVATE_KEY" "$RELAYER" --value "${FUND_MON}ether" >/dev/null
fi

echo "deploying contracts + mocks"
(cd "$ROOT/contracts" && VERIFIER=$VERIFIER TREASURY=$TREASURY KEEPER=$RELAYER OUT="deployments/$CHAIN_ID.json" \
  forge script script/DeployLocal.s.sol ${SOLC:+--use "$SOLC"} --rpc-url "$RPC_URL" --broadcast --slow \
  --private-key "$DEPLOYER_PRIVATE_KEY" >/dev/null)
DEPLOYMENT="$ROOT/contracts/deployments/$CHAIN_ID.json"
AUSD=$(jq -r .ausd "$DEPLOYMENT")
USDC=$(jq -r .usdc "$DEPLOYMENT")

echo "minting \$$TREASURY_FLOAT_USD test dollars to the treasury (gift refunds, top-up credits)"
cast send --rpc-url "$RPC_URL" --private-key "$DEPLOYER_PRIVATE_KEY" "$AUSD" "mint(address,uint256)" "$TREASURY" \
  "$((TREASURY_FLOAT_USD * 1000000))" >/dev/null

cat > "$ENV_OUT" <<ENV
# Generated by scripts/testnet-up.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Secrets — never commit.
CHAIN_ID=$CHAIN_ID
RPC_URL=$RPC_URL
DEPLOYMENT_FILE=../contracts/deployments/$CHAIN_ID.json
USDC_ADDRESS=$USDC
RELAYER_PRIVATE_KEY=$RELAYER_KEY
KEEPER_PRIVATE_KEY=$RELAYER_KEY
VERIFIER_PRIVATE_KEY=$VERIFIER_KEY
TREASURY_PRIVATE_KEY=$TREASURY_KEY
PHONE_PEPPER=$(getenv PHONE_PEPPER | grep . || rand32)
TOKEN_SECRET=$(getenv TOKEN_SECRET | grep . || rand32)
GIFT_CODE_KEY=$(getenv GIFT_CODE_KEY | grep . || rand32)
# Everything outside the chain is mocked:
OTP_PROVIDER=test
OTP_TEST_ALL=1
GIFT_PROVIDER=mock
TOPUP_PROVIDER=demo
DEV_FAUCET=1
PUBLIC_BASE_URL=${PUBLIC_BASE_URL:-http://localhost:8787}
DATABASE_PATH=data/testnet-$CHAIN_ID.db
PORT=${PORT:-8787}
ENV

echo
jq . "$DEPLOYMENT"
echo "relayer/keeper $RELAYER · verifier $VERIFIER · treasury $TREASURY"
echo "wrote $ENV_OUT — start the API with:  pnpm --filter @bilbypay/server start:testnet"
