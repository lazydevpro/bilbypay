// Writes src/queries.ts from queries/activity.graphql so the client ships the same documents
// without reading files at runtime (it also runs in React Native). Run after editing the .graphql.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function renderQueriesModule(graphql) {
  const start = graphql.search(/^query /m);
  if (start === -1) throw new Error("no query operations found");
  const operations = graphql.slice(start).trim();
  if (operations.includes("`") || operations.includes("${")) throw new Error("queries must not contain ` or ${");
  return (
    "// Generated by scripts/embed-queries.mjs from queries/activity.graphql — do not edit.\n" +
    "export const INDEXER_QUERIES = `\n" +
    operations +
    "\n`;\n"
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const graphql = readFileSync(join(root, "queries/activity.graphql"), "utf8");
  writeFileSync(join(root, "src/queries.ts"), renderQueriesModule(graphql));
  console.log("wrote indexer/src/queries.ts");
}
