// Writes packages/core/src/abis.ts from forge artifacts. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifacts = {
  bilbyDirectoryAbi: "BilbyDirectory.sol/BilbyDirectory.json",
  bilbyEscrowAbi: "BilbyEscrow.sol/BilbyEscrow.json",
  bilbyRouterAbi: "BilbyRouter.sol/BilbyRouter.json",
  erc4626Abi: "IERC4626.sol/IERC4626.json",
  erc20PermitAbi: "IERC20Permit.sol/IERC20Permit.json",
  mockAusdAbi: "MockAUSD.sol/MockAUSD.json",
  mockStataAbi: "MockStata.sol/MockStata.json",
};
let out = "// Generated by contracts/script/export-abis.mjs — do not edit.\n";
for (const [name, path] of Object.entries(artifacts)) {
  const { abi } = JSON.parse(readFileSync(join(root, "out", path), "utf8"));
  out += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(join(root, "../packages/core/src/abis.ts"), out);
console.log("wrote packages/core/src/abis.ts");
